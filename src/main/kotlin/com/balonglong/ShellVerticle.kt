class ShellVerticle : CoroutineVerticle() {
    companion object {
        val logger = LoggerFactory.getLogger(ShellVerticle::class.java)
        const val TERM_NEW_LN = "\n\r"
        const val TERM_CANCEL = "\u0003"


    }

    lateinit var server: HttpServer;
    val tempTokens = mutableMapOf<String, Long>()


    fun abc(router: Router) {


        val sockJSHandler = SockJSHandler.create(vertx)
        val route = sockJSHandler.coSocketHandler {
            val ttyConnection = SockJSTtyConnection(Charset.defaultCharset(), vertx.orCreateContext, it)
            val inputrc = Keymap::class.java.getResourceAsStream("inputrc")
            val keymap = Keymap(inputrc)
            val readline = Readline(keymap)
            readline.readline(ttyConnection, "") {
                ttyConnection.write("")
            }
        }
        router.get("/xshell/*").subRouter(route)
    }

    override suspend fun start() {
        val vertx = Vertx.newInstance(vertx)
        server = vertx.createHttpServer()
        val router = Router.router(vertx.delegate)
        val fullAccessTerminal = FullAccessTerminal()
        router.get("/static").handler(StaticHandler.create("web"))
        router.get("/uuid").handler {
            val uuid = UUID.randomUUID().toString()
            val timer = vertx.delegate.setTimer(5000) {
                tempTokens.remove(uuid)
            }
            tempTokens.put(uuid, timer)
            it.response().send(JsonObject.of("token", uuid).encode());
        }

        router.get("/xshell/*").subRouter(SockJSHandler.create(vertx.delegate)
            .coSocketHandler { sock ->
                sock.coHandler {
                    sock.pause();
                    val uuid = it.toString()
                    val timerID: Long? = tempTokens[uuid]
                    if (timerID != null) {
                        tempTokens.remove(uuid)
                        vertx.cancelTimer(timerID)
                        fullAccessTerminal.handleValidSession(sock, vertx, uuid)
                    } else {
                        logger.warn("Unauthorized access for session id {}", uuid)
                        sock.close(401, "Unauthorized")
                    }
                }
            })

        router.get("/shell/*").subRouter(SockJSHandler.create(vertx.delegate)
            .coSocketHandler { sock ->
                sock.coHandler {
                    sock.pause();
                    val uuid = it.toString()
                    val timerID: Long? = tempTokens[uuid]
                    if (timerID != null) {
                        tempTokens.remove(uuid)
                        vertx.cancelTimer(timerID)
                        handleValidSession(sock, vertx, uuid)
                    } else {
                        logger.warn("Unauthorized access for session id {}", uuid)
                        sock.close(401, "Unauthorized")
                    }
                }
            })
        server.delegate.requestHandler(router).listen(8080).coAwait()
    }

    fun exceptionHandler(throwable: Throwable, channel: ChannelShell, socket: SockJSSocket) {
        logger.warn(throwable.message, throwable)
        handleChannelClose(channel)
        socket.close(500, throwable.message)
    }

    fun handleChannelClose(channel: ChannelShell) {
        if (channel.isOpen) {
            channel.clientSession.close()
        }
    }

    override suspend fun stop() {
        server.close().awaitSuspending()
    }

    suspend fun handleValidSession(socket: SockJSSocket, vertx: Vertx, uuid: String) {
        socket.pause()
        fun logDebug(s: String, vararg markers: Any) {
            if (logger.isDebugEnabled) {
                logger.debug("Session [$uuid] : $s", markers)
            }
        }

        val contextInternal: ContextInternal = vertx.delegate.orCreateContext as ContextInternal;
        try {

            val commandFilter = CommandFilterChain()
            val request = socket.routingContext().request()
            val uri = request.uri()
            logDebug("uri {}", uri)
            val col = request.getParam("cols")
            val rows = request.getParam("rows")
            logDebug("rows {}, cols {}", rows, col)

            val client = SshClient.setUpDefaultSimpleClient()

            val address = InetSocketAddress.createUnresolved("localhost", 2222);
            val session = client.sessionLogin(address, "", "")

            val config = PtyChannelConfiguration()
//            config.ptyType = "xterm-256color"
            config.ptyType = "vt100"
            config.ptyColumns = col.toInt()
            config.ptyLines = rows.toInt()

            val channel = session.createShellChannel(config, mutableMapOf<String, Int>())

            channel.streaming = StreamingChannel.Streaming.Async
            channel.isRedirectErrorStream = true
            channel.open().verify(500)
            channel.asyncOut.toMulti(uuid).emitOn(contextInternal.executor()).subscribe().with({
                logDebug("String received from multi: {}", it)
                socket.write(it)
                if (socket.writeQueueFull()) {
                    socket.pause()
                    socket.drainHandler {
                        socket.resume()
                    }
                }
            },
                { e -> exceptionHandler(e, channel, socket) },
                { logDebug("Completed reading stream") }
            )
            val lock = ReentrantLock()

            socket.coHandler {
                lock.coWithLock {
                    logDebug("Command received {}", it)
                    val jsonObject = Json.decodeValue(it, Map::class.java)
                    val action = jsonObject["action"].toString()
                    if (action.equals("read")) {
                        val data = jsonObject.get("data").toString().toByteArray()
                        channel.asyncIn.writeBuffer(ByteArrayBuffer(data)).coAwait()
                    } else if (action.equals("resize")) {
                        val newCols = jsonObject.get("cols").toString().toInt()
                        val newRows = jsonObject.get("rows").toString().toInt()
                        logDebug("Request size change col {} row {}", newCols, newRows)
                        channel.sendWindowChange(newCols, newRows)
                    }
                }
            }
            channel.addCloseFutureListener {
                logDebug("Session closed from ssh server")
                socket.write("${TERM_NEW_LN}Session closed")
                    .onComplete {
                        socket.close()
                    }
            }
            socket.exceptionHandler {
                exceptionHandler(it, channel, socket)
            }
            socket.endHandler {
                logger.info("Session $uuid : Socket closed")
                handleChannelClose(channel)
            }
            socket.resume()
        } catch (e: Throwable) {
            socket.resume()
            socket.write("Unable to start session $uuid $TERM_NEW_LN")
            logger.warn("Session $uuid : Unable to start session due to ${e.message}");
            socket.close(500, "Unable to start session")
        }
    }

    suspend fun IoWriteFuture.coAwait() {
        val promise = Promise.promise<Void>()
        try {
            this.await(500)
            if (!this.isWritten) throw IOException("Unable to write to ssh server")
            promise.complete()
        } catch (e: Throwable) {
            promise.fail(e)
        }
        promise.future().coAwait()
    }

    fun IoInputStream.toMulti(uuid: String): Multi<Buffer> {
        val broadcaster = UnicastProcessor.create<Buffer>()
        this.addCloseFutureListener { broadcaster.onComplete() }
        read(ByteArrayBuffer()).addListener(object : SshFutureListener<IoReadFuture> {
            override fun operationComplete(future: IoReadFuture) {
                try {
                    future.await(500)
                    val vertxTempBuffer = Buffer.buffer()
                    val tempBuffer = future.buffer
                    vertxTempBuffer.appendBytes(tempBuffer.array(), tempBuffer.rpos(), tempBuffer.available());
                    tempBuffer.rpos(tempBuffer.rpos() + tempBuffer.available());
                    tempBuffer.compact();
                    broadcaster.onNext(vertxTempBuffer)
                    read(tempBuffer).addListener(this)
                } catch (e: Throwable) {
                    if (isClosing) {
                        logger.debug("Session $uuid : Read Channel closing")
                    } else {
                        broadcaster.onError(e)
                    }
                }
            }
        })
        return broadcaster
    }

    /**
     * Similar to [Router.errorHandler] but using a suspending [errorHandler].
     *
     * The coroutine context is inherited from the [CoroutineScope].
     * Additional context elements can be specified with the [context] argument.
     *
     * @param context additional context elements, [EmptyCoroutineContext] by default
     */
    fun SockJSHandler.coSocketHandler(
        context: CoroutineContext = EmptyCoroutineContext,
        handler: suspend (SockJSSocket) -> Unit
    ): Router =
        socketHandler {
            launch(it.routingContext().vertx().dispatcher() + context) {
                try {
                    handler(it)
                } catch (t: Throwable) {
                    it.routingContext().fail(t)
                }
            }
        }

    fun SockJSSocket.coHandler(
        context: CoroutineContext = EmptyCoroutineContext,
        handler: suspend (Buffer) -> Unit
    ) {
        handler {
            launch(vertx.dispatcher() + context) {
                handler(it)
            }
        }
    }

    suspend fun Lock.coWithLock(fn: suspend () -> Unit) {
        this.lock()
        try {
            fn()
        } finally {
            this.unlock()
        }
    }

}